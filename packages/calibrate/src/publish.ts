/**
 * Renders the calibration table as markdown, for `calibration/README.md`.
 *
 * Every number here comes from the table. Nothing is computed a second time and nothing
 * is rounded in a way that flatters: a rate is shown to two decimals, and an absent
 * measurement is shown as an em-free dash placeholder rather than as 0, because
 * precision over zero predictions is not zero precision.
 */

function rate(value: number | null): string {
  return value === null ? 'not measured' : value.toFixed(2);
}

function pct(value: number | null): string {
  return value === null ? 'not measured' : `${(value * 100).toFixed(1)}%`;
}

const ENGINE_LABELS: Readonly<Record<EngineId, string>> = Object.freeze({
  marlo: 'Marlo',
  'axe-core': 'axe-core',
  alfa: 'Alfa',
  htmlcs: 'HTML CodeSniffer',
});

export function renderCalibrationMarkdown(table: CalibrationTable): string {
  const lines: string[] = [];

  lines.push('# The calibration table');
  lines.push('');
  lines.push(
    'Generated by `pnpm calibrate`. Do not edit: a hand edit here is a published error rate ' +
      'turning into a marketing number, and CI fails on a table that disagrees with the harness.',
  );
  lines.push('');
  lines.push(`Generated ${table.generated} from corpus retrieved ${table.corpus.retrieved}.`);
  lines.push(
    `Renderer: \`${table.renderer}\`. Commit: ${table.commit === null ? 'a dirty tree' : `\`${table.commit}\``}.`,
  );
  lines.push('');

  lines.push('## What the two views mean');
  lines.push('');
  lines.push(
    "**ACT consistency** is W3C's official verdict, from `pages/implementations/mapping.md`. " +
      'Under that protocol `cantTell` is an allowed outcome for every example type, so an ' +
      'implementation that never commits grades as `consistent` while telling a developer nothing.',
  );
  lines.push('');
  lines.push(
    '**Strict precision and recall** count `cantTell` as no detection. That is what a user ' +
      'experiences: whether the violation will be found, and whether a clean report means clean.',
  );
  lines.push('');
  lines.push(
    'The **flattered** column marks rules where the two disagree in the direction that matters: ' +
      'officially consistent, and strict recall below 0.5. That is the column nobody publishes, ' +
      'and it is why this table has two halves. See [DECISIONS.md D-004](../DECISIONS.md#d-004).',
  );
  lines.push('');

  lines.push('## Coverage');
  lines.push('');
  lines.push(
    `Marlo implements **${String(table.coverage.implemented)} of ${String(table.coverage.publishedActRules)} published ACT rules**.`,
  );
  lines.push('');
  lines.push(
    `Of those, ${String(table.coverage.calibratable)} can be measured against official test cases.`,
  );
  if (table.coverage.implementedButUnmeasurable.length > 0) {
    lines.push('');
    lines.push(
      `${String(table.coverage.implementedButUnmeasurable.length)} implemented rule(s) have no ` +
        `official test cases and therefore cannot be calibrated: ` +
        `${table.coverage.implementedButUnmeasurable.map((r) => `\`${r}\``).join(', ')}. ` +
        'They are named rather than omitted, because leaving them out would overstate coverage ' +
        'and counting them as calibrated would overstate accuracy.',
    );
  }
  lines.push('');

  lines.push("## Marlo's own numbers");
  lines.push('');
  lines.push('| | |');
  lines.push('|---|---|');
  lines.push(`| Strict precision | ${rate(table.aggregate.strictPrecision)} |`);
  lines.push(`| Strict recall | ${rate(table.aggregate.strictRecall)} |`);
  lines.push(`| **False positive rate** | **${pct(table.aggregate.falsePositiveRate)}** |`);
  lines.push(`| Official test cases behind these | ${String(table.aggregate.sampleSize)} |`);
  lines.push('');
  lines.push(
    'The false positive rate is the number this project would most like to be small and is ' +
      'published whatever it is. A regression in it fails CI.',
  );
  lines.push('');

  lines.push('## Engines');
  lines.push('');
  lines.push('| Engine | Version | ACT rules claimed |');
  lines.push('|---|---|---|');
  for (const engine of table.engines) {
    lines.push(
      `| ${ENGINE_LABELS[engine.id]} | \`${engine.version}\` | ${String(engine.mappedRules)} |`,
    );
  }
  lines.push('');

  lines.push('## Per rule, per engine');
  lines.push('');
  lines.push(
    'Rules are listed in ACT identifier order. An engine with no mapping for a rule is omitted ' +
      'from that rule rather than shown as zero, because having no opinion and being wrong are ' +
      'different things.',
  );
  lines.push('');
  lines.push(
    '| ACT rule | Engine | Mapping | ACT verdict | Automation | Strict P | Strict R | cantTell (fail/pass) | Flattered |',
  );
  lines.push('|---|---|---|---|---|---|---|---|---|');

  const byRule = new Map<string, CalibrationEntry[]>();
  for (const entry of table.entries) {
    const list = byRule.get(entry.actRuleId) ?? [];
    list.push(entry);
    byRule.set(entry.actRuleId, list);
  }

  for (const actRuleId of [...byRule.keys()].sort()) {
    const entries = (byRule.get(actRuleId) ?? []).filter((e) => e.mappingKind !== 'none');
    if (entries.length === 0) continue;
    const rule = findRule(actRuleId);
    for (const entry of entries.sort((a, b) => a.engine.localeCompare(b.engine))) {
      lines.push(
        [
          `| [\`${actRuleId}\`](https://act-rules.github.io/rules/${actRuleId})`,
          ENGINE_LABELS[entry.engine],
          entry.mappingKind,
          entry.act.consistency,
          entry.act.automation,
          rate(entry.strict.precision),
          rate(entry.strict.recall),
          `${String(entry.strict.cantTellOnFailed)}/${String(entry.strict.cantTellOnPassed)}`,
          entry.flatteredByProtocol ? '**yes**' : 'no',
        ].join(' | ') + ' |',
      );
    }
    if (rule !== undefined) {
      lines.push(`| | | | | | | | | ${rule.name} |`);
    }
  }
  lines.push('');

  lines.push('## Routing');
  lines.push('');
  lines.push(
    'Which engine reports each rule, and whether the measurement clears the auto-fix threshold ' +
      `of ${rate(table.autoFixThreshold.minStrictPrecision)} strict precision over at least ` +
      `${String(table.autoFixThreshold.minSampleSize)} test cases.`,
  );
  lines.push('');
  lines.push('| ACT rule | Reported by | Why | Auto-fix permitted |');
  lines.push('|---|---|---|---|');
  for (const decision of [...table.routing].sort((a, b) =>
    a.actRuleId.localeCompare(b.actRuleId),
  )) {
    if (decision.chosen === null && decision.reason === 'no-implementer') continue;
    lines.push(
      `| \`${decision.actRuleId}\` | ${decision.chosen === null ? 'nobody' : ENGINE_LABELS[decision.chosen]} | ${decision.reason} | ${decision.autoFixPermitted ? 'yes' : 'no'} |`,
    );
  }
  lines.push('');

  const flattered = table.entries.filter((e) => e.flatteredByProtocol);
  lines.push('## Where the official protocol flatters an engine');
  lines.push('');
  if (flattered.length === 0) {
    lines.push(
      'No entry in this table is officially consistent while having strict recall below 0.5.',
    );
  } else {
    lines.push(
      `${String(flattered.length)} entr${flattered.length === 1 ? 'y' : 'ies'} would be reported as ` +
        'a correct implementation by the official protocol while missing more than half the ' +
        'violations a user would hit.',
    );
    lines.push('');
    lines.push('| ACT rule | Engine | ACT verdict | Strict recall |');
    lines.push('|---|---|---|---|');
    for (const entry of flattered.sort((a, b) => a.actRuleId.localeCompare(b.actRuleId))) {
      lines.push(
        `| \`${entry.actRuleId}\` | ${ENGINE_LABELS[entry.engine]} | ${entry.act.consistency} | ${rate(entry.strict.recall)} |`,
      );
    }
  }
  lines.push('');

  if (table.realCorpus !== undefined) lines.push(...renderRealCorpus(table.realCorpus, 'real'));
  if (table.heldOutCorpus !== undefined) {
    lines.push(...renderRealCorpus(table.heldOutCorpus, 'heldout'));
  }

  return `${lines.join('\n')}\n`;
}

/** Kappa and agreement to two decimals, and undefined said in words rather than as 0. */
function ratio(value: number | null): string {
  return value === null ? 'undefined' : value.toFixed(2);
}

/**
 * The `## Real pages` section. Separate from everything above it on purpose: these
 * numbers come from a different corpus and are never pooled with the ACT figures.
 */
/**
 * Who the ground truth rests on, in one sentence. A figure graded against language-model
 * ratings must say so wherever it is printed.
 */
function ratersSentence(adjudication: RealCorpus['adjudication']): string {
  const who = (r: RealCorpus['adjudication']['raters'][number]): string =>
    r.kind === 'model' ? `\`${String(r.model)}\`` : 'a person';
  const raters = adjudication.raters.map((r) => `rater ${r.rater} ${who(r)}`).join(', ');
  const models = adjudication.raters.some((r) => r.kind === 'model');
  const { person, model } = adjudication.resolutions;
  const resolved =
    person + model === 0
      ? ''
      : ` Disagreements were resolved by ${model > 0 ? 'a third model' : 'a person'}` +
        `${person > 0 && model > 0 ? ' and by a person' : ''}.`;
  return (
    `The cells were rated independently by ${raters}.${resolved}` +
    (models
      ? ' This is **model-adjudicated ground truth, not human judgment**; how accurate the ' +
        'raters are on cases with a known answer is measured in ' +
        '[RATER-VALIDITY.md](../corpus/real/adjudication/RATER-VALIDITY.md).'
      : '')
  );
}

/** A rate with its 95 percent Wilson interval, from the counts the table carries. */
function withInterval(successes: number, trials: number): string {
  const p = wilson(successes, trials);
  return p === null
    ? 'not measured'
    : `${p.value.toFixed(2)} (${p.low.toFixed(2)} to ${p.high.toFixed(2)})`;
}

function renderRealCorpus(real: RealCorpus, kind: 'real' | 'heldout'): string[] {
  const lines: string[] = [];
  const { adjudication } = real;
  const categories = real.categories.length;

  if (kind === 'real') {
    lines.push('## Real pages');
    lines.push('');
    lines.push(
      `A second corpus: ${String(real.pages)} pages in ${String(categories)} categories, ` +
        `snapshotted from the public web on ${real.retrieved} and vendored in \`corpus/real\`. ` +
        'Everything in this section is measured on those pages alone and is never pooled with ' +
        'the ACT figures above, because a precision on hand-written minimal examples and a ' +
        'precision on real pages are different claims. Pages are named by category and the ' +
        'first twelve hex digits of their SHA-256; ' +
        '[corpus/real/NOTICE.md](../corpus/real/NOTICE.md) says why, and the manifest has the URLs. ' +
        "Marlo's errors on these pages were analysed cell by cell in " +
        '[ERROR-ANALYSIS.md](ERROR-ANALYSIS.md), so a rule corrected after that analysis scores ' +
        'in-sample here. The held-out pages below are the out-of-sample check.',
    );
  } else {
    lines.push('## Held-out real pages');
    lines.push('');
    lines.push(
      `A third corpus: ${String(real.pages)} pages in ${String(categories)} categories from ` +
        'sites `corpus/real` does not use, snapshotted the same way on ' +
        `${real.retrieved} and vendored in \`corpus/heldout\`. Their ground truth was rated ` +
        'under the same protocol by the same raters and committed before any rule change ' +
        "made after the error analysis was measured on them, so for Marlo's corrected rules " +
        'this is the out-of-sample figure. It is never pooled with the sections above. ' +
        '[corpus/heldout/NOTICE.md](../corpus/heldout/NOTICE.md) has the attributions.',
    );
  }
  lines.push('');

  lines.push('### Ground truth');
  lines.push('');
  lines.push(
    `${String(adjudication.ratedCells)} of ${String(adjudication.totalCells)} cells (pages ` +
      'times the rules Marlo implements) have been rated by both raters, and ' +
      `${String(adjudication.resolvedCells)} have a resolved ground truth. Status: ` +
      `\`${adjudication.status}\`.`,
  );
  lines.push('');
  if (adjudication.resolvedCells === 0) {
    lines.push(
      '**No accuracy figure exists for these pages yet**, and none will until two raters ' +
        'have rated them independently under ' +
        '[the adjudication protocol](../corpus/real/adjudication/PROTOCOL.md). ' +
        'The figures below need no ground truth.',
    );
  } else {
    lines.push(
      `${ratersSentence(adjudication)} Inter-rater agreement over the rated cells: ` +
        `${pct(adjudication.percentAgreement)}, Cohen's kappa ${ratio(adjudication.kappa)}. ` +
        'Marlo against the resolved cells only:',
    );
    lines.push('');
    lines.push('| | |');
    lines.push('|---|---|');
    lines.push(`| Strict precision | ${rate(real.aggregate.accuracy.strictPrecision)} |`);
    lines.push(`| Strict recall | ${rate(real.aggregate.accuracy.strictRecall)} |`);
    lines.push(`| False positive rate | ${pct(real.aggregate.accuracy.falsePositiveRate)} |`);
    lines.push(`| Resolved cells behind these | ${String(real.aggregate.accuracy.sampleSize)} |`);
  }
  lines.push('');

  const engines = real.aggregate.engines ?? [];
  if (engines.length > 0) {
    lines.push('### Every engine on the resolved cells');
    lines.push('');
    lines.push(
      'Strict grading, as in the ACT table: a cantTell on a failed cell is a miss, and an ' +
        'unsupported rule reports nothing. Each engine is pooled over the rules it claims among ' +
        'the ones Marlo implements, so the rule counts differ. Intervals are 95 percent Wilson ' +
        'intervals from the counts.',
    );
    lines.push('');
    lines.push(
      '| Engine | Rules | True positives | False positives | False negatives | Strict precision | Strict recall | False positive rate |',
    );
    lines.push('|---|---|---|---|---|---|---|---|');
    for (const row of engines) {
      lines.push(
        `| ${ENGINE_LABELS[row.engine]} | ${String(row.rules)} | ${String(row.truePositives)} | ` +
          `${String(row.falsePositives)} | ${String(row.falseNegatives)} | ` +
          `${withInterval(row.truePositives, row.truePositives + row.falsePositives)} | ` +
          `${withInterval(row.truePositives, row.truePositives + row.falseNegatives)} | ` +
          `${pct(row.falsePositiveRate)} |`,
      );
    }
    lines.push('');
  }

  lines.push('### Findings per page');
  lines.push('');
  lines.push(
    'A finding is one element one engine flagged as failing one rule, over the rules that ' +
      'engine claims. Engines claim different numbers of rules, so this compares volume, not ' +
      'accuracy. A page where an engine reported an error on any rule, crashed, or ran out of ' +
      'time is excluded from its mean and counted in the last column, never read as clean.',
  );
  lines.push('');
  lines.push('| Engine | Pages finished | Findings | Mean per page | Pages errored |');
  lines.push('|---|---|---|---|---|');
  for (const row of real.aggregate.findingsPerPage) {
    lines.push(
      `| ${ENGINE_LABELS[row.engine]} | ${String(row.pages)} | ${String(row.findings)} | ` +
        `${row.mean === null ? 'not measured' : row.mean.toFixed(2)} | ${String(real.pages - row.pages)} |`,
    );
  }
  lines.push('');

  const { invariant } = real.aggregate;
  lines.push('### The one-directional invariant');
  lines.push('');
  lines.push(
    `On ${String(invariant.pagesWhereItWouldFire)} of ${String(invariant.pages)} pages ` +
      `(${pct(invariant.fraction)}), at least one rule has a peer engine reporting a failure ` +
      'where the engine routing chose for that rule does not, so the invariant would override ' +
      'the routed verdict. Routing is the one the ACT table above produced.',
  );
  lines.push('');
  const firing = invariant.perRule.filter((r) => r.pagesWhereItWouldFire > 0);
  if (firing.length > 0) {
    lines.push('| ACT rule | Routed to | Pages where it would fire |');
    lines.push('|---|---|---|');
    for (const row of firing) {
      lines.push(
        `| \`${row.actRuleId}\` | ${row.routedTo === null ? 'nobody' : ENGINE_LABELS[row.routedTo]} | ` +
          `${String(row.pagesWhereItWouldFire)} |`,
      );
    }
    lines.push('');
  }

  lines.push('### Agreement between engines');
  lines.push('');
  lines.push(
    'Per rule, for each pair of engines that both claim it, over the pages where both returned ' +
      "an outcome: how often they gave the same one, and Cohen's kappa, which discounts the " +
      'agreement two engines would reach by chance. Two engines that disagree cannot both be ' +
      'right, so a low figure marks a rule worth a human look, though not which engine is wrong. ' +
      'Kappa is undefined when both engines gave one identical answer on every page.',
  );
  lines.push('');
  lines.push('| ACT rule | Engines | Pages | Agreement | Kappa |');
  lines.push('|---|---|---|---|---|');
  for (const row of real.agreement) {
    lines.push(
      `| \`${row.actRuleId}\` | ${ENGINE_LABELS[row.engines[0]]} and ${ENGINE_LABELS[row.engines[1]]} | ` +
        `${String(row.pages)} | ${pct(row.percentAgreement)} | ${ratio(row.kappa)} |`,
    );
  }
  lines.push('');
  return lines;
}

/**
 * Every leaf of the real-page block that differs between two tables, for `--check`.
 *
 * These figures carry no direction to call better or worse until ground truth exists, so
 * any movement fails the check, in either direction. A number that moved for no recorded
 * reason is the thing to investigate, whichever way it went.
 */
export function findRealCorpusChanges(
  before: CalibrationTable,
  after: CalibrationTable,
  limit = 40,
): readonly string[] {
  const flatten = (value: unknown, path: string, out: Map<string, string>): void => {
    if (value !== null && typeof value === 'object') {
      for (const [key, child] of Object.entries(value)) flatten(child, `${path}.${key}`, out);
    } else {
      out.set(path, JSON.stringify(value));
    }
  };
  const left = new Map<string, string>();
  const right = new Map<string, string>();
  flatten(before.realCorpus ?? null, 'realCorpus', left);
  flatten(after.realCorpus ?? null, 'realCorpus', right);
  flatten(before.heldOutCorpus ?? null, 'heldOutCorpus', left);
  flatten(after.heldOutCorpus ?? null, 'heldOutCorpus', right);
  const changes: string[] = [];
  for (const key of [...new Set([...left.keys(), ...right.keys()])].sort()) {
    if (left.get(key) === right.get(key)) continue;
    changes.push(`${key}: ${left.get(key) ?? 'absent'} -> ${right.get(key) ?? 'absent'}`);
  }
  return changes.length > limit
    ? [...changes.slice(0, limit), `...and ${String(changes.length - limit)} more`]
    : changes;
}

/** A regression in any published number, for the CI gate. */
export interface Regression {
  readonly what: string;
  readonly before: string;
  readonly after: string;
}

/**
 * Compares a freshly generated table against the committed one.
 *
 * Fails on a worse false positive rate, worse aggregate precision or recall, a shrunken
 * coverage numerator, or a rule that stopped being routable. Does not fail on
 * improvements, and reports them, because a silent improvement is a number nobody
 * updated the README for.
 */
export function findRegressions(
  before: CalibrationTable,
  after: CalibrationTable,
): { readonly regressions: readonly Regression[]; readonly improvements: readonly Regression[] } {
  const regressions: Regression[] = [];
  const improvements: Regression[] = [];

  const compare = (
    what: string,
    a: number | null,
    b: number | null,
    higherIsBetter: boolean,
  ): void => {
    if (a === null || b === null) return;
    // A tolerance, because floating point arithmetic over pooled counts is not exact and
    // a diff of 1e-15 is not a regression.
    if (Math.abs(a - b) < 1e-9) return;
    const worse = higherIsBetter ? b < a : b > a;
    const record = { what, before: a.toFixed(4), after: b.toFixed(4) };
    if (worse) regressions.push(record);
    else improvements.push(record);
  };

  compare(
    'aggregate strict precision',
    before.aggregate.strictPrecision,
    after.aggregate.strictPrecision,
    true,
  );
  compare(
    'aggregate strict recall',
    before.aggregate.strictRecall,
    after.aggregate.strictRecall,
    true,
  );
  compare(
    'false positive rate',
    before.aggregate.falsePositiveRate,
    after.aggregate.falsePositiveRate,
    false,
  );

  if (after.coverage.implemented < before.coverage.implemented) {
    regressions.push({
      what: 'coverage numerator',
      before: String(before.coverage.implemented),
      after: String(after.coverage.implemented),
    });
  }

  const routedBefore = new Set(
    before.routing.filter((r) => r.chosen !== null).map((r) => r.actRuleId),
  );
  const routedAfter = new Set(
    after.routing.filter((r) => r.chosen !== null).map((r) => r.actRuleId),
  );
  for (const actRuleId of routedBefore) {
    if (!routedAfter.has(actRuleId)) {
      regressions.push({
        what: `rule ${actRuleId} is no longer routable to any engine`,
        before: 'routed',
        after: 'no engine',
      });
    }
  }

  return { regressions, improvements };
}

/**
 * Renders the analysis as markdown, for `calibration/ANALYSIS.md`.
 *
 * Every figure comes from the analysis artifact, and every proportion is printed with its
 * interval, because a precision over a dozen cases without one claims more than it knows.
 */
export function renderAnalysisMarkdown(analysis: AnalysisReport): string {
  const lines: string[] = [];
  const rateOf = (p: Proportion | null): string =>
    p === null
      ? 'not measured'
      : `${p.value.toFixed(3)} (${p.low.toFixed(3)} to ${p.high.toFixed(3)})`;
  const pctOf = (p: Proportion | null): string =>
    p === null
      ? 'not measured'
      : `${(p.value * 100).toFixed(1)}% (${(p.low * 100).toFixed(1)} to ${(p.high * 100).toFixed(1)})`;
  const strategyTable = (strategies: readonly StrategyScore[]): void => {
    lines.push('| Strategy | Precision | Recall | False positive rate | TP | FP | FN | TN |');
    lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const s of strategies) {
      lines.push(
        `| ${s.label} | ${rateOf(s.precision)} | ${rateOf(s.recall)} | ${pctOf(s.falsePositiveRate)} | ` +
          `${String(s.truePositives)} | ${String(s.falsePositives)} | ${String(s.falseNegatives)} | ${String(s.trueNegatives)} |`,
      );
    }
    lines.push('');
  };

  lines.push(
    `# The analysis behind the calibration table${analysis.renderer === 'browser' ? ', in Chromium' : ''}`,
  );
  lines.push('');
  lines.push(
    'Generated by `pnpm calibrate` from the same harness pass as the table, case by case. ' +
      'Do not edit: `pnpm calibrate --check` regenerates it and fails if any figure moved.',
  );
  lines.push('');
  lines.push(
    `Generated ${analysis.generated}. Renderer: \`${analysis.renderer}\`. ` +
      `Commit: ${analysis.commit === null ? 'a dirty tree' : `\`${analysis.commit}\``}. ` +
      'Every interval is a Wilson score interval at 95 percent.',
  );
  lines.push('');
  lines.push('## Why this exists');
  lines.push('');
  lines.push(
    "The table's routing is chosen from the same per-rule grades the table publishes, and the " +
      'router refuses any engine that flagged a passing case. Scoring the routed engine on those ' +
      'same cases is an in-sample figure, optimistic by construction. The figures below score ' +
      'the router on cases it did not see, and measure what `marlo scan` reports as a whole.',
  );
  lines.push('');
  for (const scope of analysis.scopes) {
    lines.push(
      scope.id === 'scan'
        ? `## What marlo scan reports: ${String(scope.rules)} rules, ${String(scope.cases)} cases`
        : `## Every routed rule: ${String(scope.rules)} rules, ${String(scope.cases)} cases`,
    );
    lines.push('');
    lines.push(scope.description);
    lines.push('');
    strategyTable(scope.strategies);
    for (const s of scope.strategies) lines.push(`- **${s.label}.** ${s.description}`);
    lines.push('');
  }
  const stability = analysis.routingStability;
  lines.push('## How stable the routing is');
  lines.push('');
  lines.push(
    `Holding one case out changes the router's choice on ${String(stability.casesWhereChoiceChanges)} ` +
      `of ${String(stability.cases)} cases, across ${String(stability.rulesWhereChoiceChanges.length)} rules` +
      (stability.rulesWhereChoiceChanges.length === 0
        ? '.'
        : `: ${stability.rulesWhereChoiceChanges.map((r) => `\`${r}\``).join(', ')}.`),
  );
  lines.push('');
  lines.push('## Agreement between engines on the official cases');
  lines.push('');
  lines.push(
    'Cohen\'s kappa over the cases both engines answered, on all four outcomes and on "failed or not".',
  );
  lines.push('');
  lines.push('| Engines | Cases | Agreement | Kappa | Kappa, failed or not |');
  lines.push('| --- | --- | --- | --- | --- |');
  const num = (x: number | null): string => (x === null ? 'undefined' : x.toFixed(3));
  for (const a of analysis.agreement) {
    lines.push(
      `| ${a.engines[0]} and ${a.engines[1]} | ${String(a.cases)} | ${num(a.percentAgreement)} | ${num(a.kappa)} | ${num(a.kappaFailed)} |`,
    );
  }
  lines.push('');
  lines.push('## Routing scored on the real pages');
  lines.push('');
  if (analysis.realPages === null) {
    lines.push(
      'Not yet. This is the other held-out design: the routing chosen on the official corpus, ' +
        'scored on real pages it never saw. It needs rated pages, and none are, ' +
        'so there is nothing to score against.',
    );
  } else {
    lines.push(
      `Over ${String(analysis.realPages.resolvedCells)} resolved cells, with the routing chosen on the official corpus.`,
    );
    lines.push('');
    strategyTable(analysis.realPages.strategies);
  }
  lines.push('');
  lines.push('## How much the flattered column depends on its threshold');
  lines.push('');
  lines.push('| Strict recall below | Entries graded consistent | Of them Marlo |');
  lines.push('| --- | --- | --- |');
  for (const f of analysis.flatterySensitivity) {
    lines.push(
      `| ${f.recallBelow.toFixed(2)} | ${String(f.entries)} | ${String(f.marloEntries)} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}
